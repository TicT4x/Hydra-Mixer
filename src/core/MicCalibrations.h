/** The presets, in the order they are offered. The data sheet's low end (-7.6 dB at 100 Hz, -15 dB at 60 Hz)
    contradicts its own spec (frequency range 20 Hz - 20 kHz at -10 dB) and looks like the gated (quasi-anechoic)
    measurement it was made with, which cannot resolve low frequencies. Taken at face value it would show every
    room with up to +15 dB too much bass. So the default preset uses the curve from 500 Hz up (presence peak
    +5.6 dB at 5.6 kHz, +4.5 dB at 8 kHz) and treats the microphone as flat below; the second one uses all of it. */
inline std::vector<Calibration> builtInCalibrations()
{
    std::vector<Calibration> list;
    Calibration em700;
    em700.name = "t.bone EM 700 (data sheet, from 500 Hz)";
    for (auto& p : tboneEm700DataSheet())
        if (p.first >= 500.0) em700.points.push_back (p);
    list.push_back (em700);

    Calibration full;
    full.name = "t.bone EM 700 (full data sheet curve)";
    full.points = tboneEm700DataSheet();
    list.push_back (full);
    return list;
}
